    'site:boards.greenhouse.io ("Engineering Manager" OR "Senior Engineering Manager" OR "Staff Engineer") ("remote" OR "san francisco" OR "new york") ("react" OR "typescript" OR "graphql" OR "aws") ("fintech" OR "healthtech" OR "edtech")',
