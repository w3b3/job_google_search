  console.log(`   Positions: [${strictConfig.position.join(', ')}]`);
  console.log(`   Locations: [${strictConfig.location.join(', ')}]`);
  console.log(`   Technologies: [${strictConfig.technology.join(', ')}]`);
  console.log(`   Domains: [${strictConfig.domain.join(', ')}]`);
  console.log(`   ATS Platforms: [${strictConfig.atsplatforms.join(', ')}]`);

